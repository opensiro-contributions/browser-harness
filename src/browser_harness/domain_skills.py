"""Export existing agent-written domain skills as individually indexable SKILL.md entries.

This is an explicit, offline conversion for agent systems that index SKILL.md
files. It does not generate skills, run an agent, or touch a browser daemon.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import tempfile
from pathlib import Path

from . import paths

_PREFIX = "browser-harness-"
_MARKER = "<!-- browser-harness-domain-skill-export:v1 source="
_MAX_NAME = 120


class ExportError(ValueError):
    """An export would overwrite unrelated or modified user content."""


def _name(relative: Path) -> str:
    pieces = [
        re.sub(r"[^a-z0-9]+", "-", part.lower()).strip("-")
        for part in relative.with_suffix("").parts
    ]
    if not pieces or any(not part for part in pieces):
        raise ExportError(f"Cannot make a skill name from {relative}")
    result = _PREFIX + "-".join(pieces)
    if len(result) > _MAX_NAME:
        raise ExportError(f"Skill name too long for {relative}")
    return result


def _render(relative: Path, name: str, body: str) -> str:
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    source = json.dumps(relative.as_posix(), ensure_ascii=True)
    desc = json.dumps(
        f"Browser Harness domain skill for {relative.with_suffix('').as_posix().replace('/', ' / ')}",
        ensure_ascii=True,
    )
    return (
        f"---\nname: {name}\ndescription: {desc}\n---\n\n"
        f"{_MARKER}{source} sha256={digest} -->\n\n{body}"
    )


def _is_unmodified_export(existing: str, relative: Path, name: str) -> bool:
    """Verify *all* prior generated bytes, including metadata and body."""
    marker = f"{_MARKER}{json.dumps(relative.as_posix(), ensure_ascii=True)} sha256="
    pos = existing.find(marker)
    if pos < 0:
        return False
    start = existing.find(" -->\n\n", pos)
    if start < 0:
        return False
    body = existing[start + len(" -->\n\n"):]
    return existing == _render(relative, name, body)


def _source_files(root: Path) -> list[Path]:
    if not root.is_dir() or root.is_symlink():
        raise ExportError(f"Domain skills directory missing or symbolic: {root}")
    files = sorted(root.rglob("*.md"))
    if not files:
        raise ExportError(f"No domain-skill Markdown files found in {root}")
    for file in files:
        if file.is_symlink() or any(p.is_symlink() for p in file.parents if p != root):
            raise ExportError(f"Refusing symbolic source: {file}")
        if not file.is_file():
            raise ExportError(f"Not a regular domain-skill file: {file}")
    return files


def export_domain_skills(source_root: Path, output: Path, *, update_managed: bool = False) -> dict[str, int]:
    """Preflight all outputs before writing; never replace unmanaged/edited skills."""
    root = Path(source_root).expanduser().absolute()
    requested = Path(output).expanduser()
    if requested.is_symlink():
        raise ExportError(f"Refusing symbolic output root: {requested}")
    destination = requested.absolute()
    if destination == root or root in destination.parents:
        raise ExportError("Output must be outside the source domain-skills tree")

    changes: list[tuple[Path, str]] = []
    names: set[str] = set()
    unchanged = 0
    for src in _source_files(root):
        relative = src.relative_to(root)
        name = _name(relative)
        if name in names:
            raise ExportError(f"Colliding skill name: {name}")
        names.add(name)
        body = src.read_text(encoding="utf-8")
        if not body.endswith("\n"):
            body += "\n"
        expected = _render(relative, name, body)
        directory = destination / name
        target = directory / "SKILL.md"
        if directory.is_symlink() or target.is_symlink():
            raise ExportError(f"Refusing symbolic destination: {target}")
        if target.exists():
            if not target.is_file():
                raise ExportError(f"Not a regular target: {target}")
            previous = target.read_text(encoding="utf-8")
            if previous == expected:
                unchanged += 1
                continue
            if not update_managed or not _is_unmodified_export(previous, relative, name):
                raise ExportError(f"Refusing to overwrite unmanaged or modified skill: {target}")
        changes.append((target, expected))

    # All collisions/conflicts are detected before touching destination.
    for target, expected in changes:
        target.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(prefix=".SKILL.md-", dir=target.parent)
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(expected)
            os.replace(tmp, target)
        finally:
            if os.path.exists(tmp):
                os.unlink(tmp)
    return {"exported": len(changes), "unchanged": unchanged, "total": len(names)}


def run_cli(args: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="browser-harness domain-skills")
    command = parser.add_subparsers(dest="command", required=True)
    exp = command.add_parser("export", help="export site-specific Markdown as indexable SKILL.md files")
    exp.add_argument("--output", type=Path, required=True, help="explicit external skill-index directory")
    exp.add_argument("--update-managed", action="store_true", help="refresh only intact, previously exported entries")
    ns = parser.parse_args(args)
    try:
        stats = export_domain_skills(
            paths.workspace_dir() / "domain-skills", ns.output, update_managed=ns.update_managed
        )
    except (ExportError, UnicodeError, OSError) as exc:
        parser.exit(1, f"domain-skills: {exc}\n")
    print(f"domain-skills: exported={stats['exported']} unchanged={stats['unchanged']} total={stats['total']}")
    return 0
